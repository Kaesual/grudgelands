-- Round 54 lane WEB: the test character of the kaesual handoff, as the game
-- composes it, and the capture scene that photographs it.
--
-- Loads the real game files through the web export's loader
-- (tools/web_data/build.lua) and composes one character with the game's own
-- functions (grug_visuals.compose, appearance, appearance_json): a human in
-- the metal line's top tier (abyssal steel) on every slot, the chest
-- enchanted (prefix Strength, suffix Dexterity), the boots broken, a plain
-- abyssal steel sword in the main hand and the hunter cloak. Writes
--   tools/r54_web/test_character.json  the stored appearance value, exactly
--                                      as the game writes it to player meta;
--   tools/r54_web/scene.lua            the scene for tools/r54_model/capture.sh
--                                      (the textures embedded): the exported
--                                      .glb beside the game's .b3d, and the
--                                      game's own look with the hand entity.
--
--   luajit tools/r54_web/gen_test_character.lua           # rewrite both
--   luajit tools/r54_web/gen_test_character.lua --check   # exit 1 if stale
--
-- The shots (one boot, through the shared Lua queue):
--   M=$(mktemp -d); cp tools/web_data/model/grug_visuals_character.glb "$M"
--   SCENE=tools/r54_web/scene.lua MODELS="$M" XVFB=... tools/r54_model/capture.sh OUT

local ROOT, mode = ".", "write"
for _, value in ipairs(arg or {}) do
	if value == "--check" then mode = "check" else ROOT = value end
end
local DIR = ROOT .. "/tools/r54_web/"

local web_data = dofile(ROOT .. "/tools/web_data/build.lua")
web_data.build(ROOT)
local gv = grug_visuals
local items = core.registered_items
gv.index_armor(items)

local RACE = "human"
local LOOK = {tone = 2, hair = 4, style = 2, eyes = 1, feature = 1}
local CLOAK_ID = "hunter_2"
local CLOAK = "grug_achievements_cloak_hunter_2.png"
local LINE, GRADE = "metal", "abyssal_steel"
local SWORD = "grug_gear:sword_abyssal_steel"
local ENCHANT = {chest = {{channel = "prefix", stat = "str"}, {channel = "suffix", stat = "dex"}}}
local BROKEN = {feet = true}

local armor, worn, enchants = {}, {}, {}
for _, slot in ipairs(gv.SLOTS) do
	local name = "grug_gear:" .. slot .. "_" .. LINE .. "_" .. GRADE
	assert(gv.armor_appearance[name], "gen_test_character: unknown " .. name)
	armor[slot] = name
	worn[slot] = {name = name, affixes = ENCHANT[slot] or {}}
end
local spec = {race = RACE, look = LOOK, armor = armor, armor_broken = BROKEN, worn = worn,
	armor_enchant = gv.armor_enchants(worn)}
local result = gv.compose(spec)
local data = gv.appearance(spec, result, CLOAK, CLOAK_ID)

-- The main hand as apply.lua stores it (grug_visuals.hand_image of a plain
-- stack: the definition's images, no stack meta).
local def = assert(items[SWORD], "gen_test_character: unknown " .. SWORD)
local function group(name, g)
	local d = items[name]
	return d and d.groups and d.groups[g] or 0
end
local image = def._grug_world_wield_image or def.wield_image or def.inventory_image
data.slots.mainhand = {item = SWORD, broken = false, enchant = {},
	pose = gv.pose_for(SWORD, group, def._grug_wield_pose), image = image}
-- The capture probe's hand entity holds the tool pose, the sword's own.
assert(data.slots.mainhand.pose == "tool", "gen_test_character: the sword is not in the tool pose")
local json = gv.appearance_json(data)
assert(#json <= gv.APPEARANCE_JSON_MAX, "gen_test_character: over the JSON cap")

local function quote(text)
	return ("%q"):format(text):gsub("\\\n", "\\n")
end

local scene = ([[
-- Generated by tools/r54_web/gen_test_character.lua; do not edit. The scene
-- of the kaesual handoff's test character for tools/r54_model/capture.sh
-- (MODELS= a directory with tools/web_data/model/grug_visuals_character.glb):
-- R* the exported .glb (left) beside the game's .b3d (right), both with the
-- character's four textures (the weapon card empty, as in the world) at the
-- stand pose's frame 0; G* the game's look: the .b3d with the hand entity
-- holding the sword in its pose (%s), standing and walking. The camera looks
-- along +z; a figure at yaw pi faces it.
local GLB, B3D = "grug_visuals_character.glb", "grug_visuals_character.b3d"
local TEXTURES = {
	%s,
	%s,
	%s,
	"blank.png",
}
local SWORD = %s
local PI = math.pi
local STAND, WALK, WALK_OTHER = 0, 172, 182
local NEAR, FAR = {0, 0.5, -2.6}, {0, 0.5, -3.4}

local function pair(yaw)
	return {
		{at = {-0.6, 0.5, 0}, yaw = yaw, frame = STAND, mesh = GLB, textures = TEXTURES},
		{at = {0.6, 0.5, 0}, yaw = yaw, frame = STAND, mesh = B3D, textures = TEXTURES},
	}
end

local function game(at, yaw, frame)
	return {at = at, yaw = yaw, frame = frame, mesh = B3D, textures = TEXTURES, wield = SWORD}
end

return {
	shots = {
		{name = "R1_glb_b3d_front", cam = NEAR, pitch = 0.25, figures = pair(PI)},
		{name = "R2_glb_b3d_3q", cam = NEAR, pitch = 0.25, figures = pair(PI * 0.75)},
		{name = "R3_glb_b3d_side", cam = NEAR, pitch = 0.25, figures = pair(PI / 2)},
		{name = "R4_glb_b3d_back", cam = NEAR, pitch = 0.25, figures = pair(0)},
		{name = "G1_game_front_3q_walk", cam = FAR, pitch = 0.18, figures = {
			game({-1.4, 0.5, 0}, PI, STAND),
			game({0, 0.5, 0}, PI * 0.75, STAND),
			game({1.4, 0.5, 0}, PI * 0.75, WALK),
		}},
		{name = "G2_game_back_side_walk", cam = FAR, pitch = 0.18, figures = {
			game({-1.4, 0.5, 0}, 0, STAND),
			game({0, 0.5, 0}, PI / 2, STAND),
			game({1.4, 0.5, 0}, -PI / 2, WALK_OTHER),
		}},
		{name = "G3_game_close_front", cam = {0, 0.5, -1.9}, pitch = 0.3, figures = {
			game({0, 0.5, 0}, PI * 0.85, STAND),
		}},
	},
}
]]):format(data.slots.mainhand.pose, quote(data.textures.body), quote(CLOAK),
	quote(data.textures.armor), quote(SWORD))

local outputs = {["test_character.json"] = json .. "\n", ["scene.lua"] = scene}
local stale = false
for _, name in ipairs({"test_character.json", "scene.lua"}) do
	local path = DIR .. name
	if mode == "check" then
		local handle = io.open(path, "rb")
		local committed = handle and handle:read("*a")
		if handle then handle:close() end
		if committed ~= outputs[name] then
			print("gen_test_character: " .. path .. " is stale")
			stale = true
		end
	else
		local handle = assert(io.open(path, "wb"))
		handle:write(outputs[name])
		handle:close()
		print("gen_test_character: wrote " .. path .. " (" .. #outputs[name] .. " bytes)")
	end
end
if stale then
	os.exit(1)
end
if mode == "check" then
	print("gen_test_character: up to date")
end
print(("body %d, armor %d, JSON %d bytes"):format(#data.textures.body, #data.textures.armor, #json))
