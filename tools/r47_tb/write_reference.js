// Round 47 lane TB: writes the JS reference for the Lua tree generator port.
//
//   node tools/r47_tb/write_reference.js           (writes reference.lua)
//   node tools/r47_tb/write_reference.js --check   (exit 1 when it is stale)
//
// From tools/r46_tree/concept/treegen.js, for every species and the 300
// seeds of SEEDS: the digest of the tree on flat ground (no ground
// callback) and, for the species with roots (apple, jungle, kapok), on the
// bumpy ground below; the Shapes view's root study for three cases; the
// canonical serialisation of a few full trees; and
// the digest of treegen.js itself, so the fixture notices a changed
// generator. tools/r47_tb/portable_test.lua compares the Lua port against
// it without node.
//
// Canonical serialisation of a tree: one line "x y z kind rot" per node in
// the list's (sorted) order, then one line "root x y z" per root cell in
// placing order. The digest is "<nodes>/<roots>/<h1>/<h2>": two polynomial
// hashes mod 2^31 - 1 over the integers x, y, z, kind code, rot of every
// node and x, y, z of every root cell (each fed as v + 1000, so every `%`
// sees a non-negative left operand and JS and Lua agree).
'use strict';
var fs = require('fs');
var path = require('path');

var REPO = path.join(__dirname, '..', '..');
var SOURCE = path.join(REPO, 'tools', 'r46_tree', 'concept', 'treegen.js');
var OUT = path.join(__dirname, 'reference.lua');
var G = require(SOURCE);

var M = 2147483647;
var KIND = {trunk: 1, quarter: 2, base: 3, branch: 4, twig: 5, leaves: 6, fruit: 7, moss: 8};

function Digest() { this.h1 = 0; this.h2 = 0; }
Digest.prototype.feed = function (v) {
	this.h1 = (this.h1 * 1000003 + v + 1000) % M;
	this.h2 = (this.h2 * 69069 + v + 1000) % M;
};

function treeDigest(tree) {
	var d = new Digest();
	tree.nodes.forEach(function (n) {
		if (KIND[n.kind] === undefined) { throw new Error('unknown kind ' + n.kind); }
		d.feed(n.x); d.feed(n.y); d.feed(n.z); d.feed(KIND[n.kind]); d.feed(n.rot);
	});
	tree.roots.forEach(function (r) { d.feed(r[0]); d.feed(r[1]); d.feed(r[2]); });
	return tree.nodes.length + '/' + tree.roots.length + '/' + d.h1 + '/' + d.h2;
}

function serialise(tree) {
	var lines = tree.nodes.map(function (n) { return n.x + ' ' + n.y + ' ' + n.z + ' ' + n.kind + ' ' + n.rot; });
	tree.roots.forEach(function (r) { lines.push('root ' + r[0] + ' ' + r[1] + ' ' + r[2]); });
	return lines.join('\n') + '\n';
}

// The bumpy ground: per column the top lies at the foot level (5 in 7), one
// lower or one higher (1 in 7 each), so some roots are placed, some find no
// ground and some find ground in their way.
function bumpy(seed) {
	var s = ((seed % 1000) + 1000) % 1000;
	return function (x, y, z) {
		var r = ((x + 50) * 7919 + (z + 50) * 104729 + s * 31) % 7;
		return y < (r === 0 ? -1 : (r === 1 ? 1 : 0));
	};
}

// 1..200, the edges of the seed range, and 91 seeds spread over it.
var SEEDS = [];
for (var i = 1; i <= 200; i++) { SEEDS.push(i); }
[0, -1, -7, 2147483644, 2147483645, 2147483646, 2147483647, 4294967301, 9007199254740991].forEach(function (s) {
	SEEDS.push(s);
});
var spread = 12345;
for (var j = 0; j < 91; j++) { spread = (spread * 48271) % M; SEEDS.push(spread); }

// Seeds that must give the same tree (period 2^31 - 2 of the exponent,
// every seed below -1 like -1).
var SAME = [[2147483646, 0], [2147483645, -1], [-7, -1], [2147483647, 1]];

var ROOTED = ['apple', 'jungle', 'kapok'];
var FULL = [['apple', 1, 'flat'], ['jungle', 1, 'flat'], ['kapok', 1, 'flat'], ['kapok', 1, 'bumpy'],
	['acacia', 1, 'flat'], ['pine', 1, 'flat'], ['aspen', 1, 'flat'], ['silverwood', 1, 'flat'],
	['gravewood', 1, 'flat'], ['swamp', 1, 'flat']];

// The Shapes view's root study: [ground, trunk width, per side [h, reach,
// fork] or null, bumpy seed].
function flatGround(x, y, z) { return y < 0; }
var STUDY = [['flat', 2, [[0, 2, 0], [2, 2, 1], [3, 3, -1], null], 0],
	['flat', 3, [[3, 3, 1], [0, 3, -1], [2, 2, 0], [3, 2, 1]], 0],
	['bumpy', 3, [[2, 3, 1], [3, 3, -1], [0, 2, 1], [2, 3, -1]], 5]];

function sourceDigest() {
	var bytes = fs.readFileSync(SOURCE);
	var d = new Digest();
	for (var k = 0; k < bytes.length; k++) { d.feed(bytes[k]); }
	return bytes.length + '/' + d.h1 + '/' + d.h2;
}

function build() {
	var out = [];
	out.push('-- Generated by tools/r47_tb/write_reference.js from tools/r46_tree/concept/treegen.js;');
	out.push('-- do not edit. Rerun the writer after any change to treegen.js.');
	out.push('return {');
	out.push('\tsource = "' + sourceDigest() + '",');
	out.push('\tseeds = {' + SEEDS.join(', ') + '},');
	out.push('\tsame = {' + SAME.map(function (p) { return '{' + p[0] + ', ' + p[1] + '}'; }).join(', ') + '},');
	out.push('\trooted = {' + ROOTED.map(function (s) { return '"' + s + '"'; }).join(', ') + '},');
	out.push('\tflat = {');
	G.ORDER.forEach(function (sp) {
		var list = SEEDS.map(function (s) { return '"' + treeDigest(G.generate(sp, s)) + '"'; });
		out.push('\t\t' + sp + ' = {' + list.join(', ') + '},');
		SAME.forEach(function (p) {
			if (treeDigest(G.generate(sp, p[0])) !== treeDigest(G.generate(sp, p[1]))) {
				throw new Error(sp + ' seeds ' + p[0] + ' and ' + p[1] + ' differ');
			}
		});
	});
	out.push('\t},');
	out.push('\tbumpy = {');
	ROOTED.forEach(function (sp) {
		var list = SEEDS.map(function (s) { return '"' + treeDigest(G.generate(sp, s, bumpy(s))) + '"'; });
		out.push('\t\t' + sp + ' = {' + list.join(', ') + '},');
	});
	out.push('\t},');
	out.push('\tstudy = {');
	STUDY.forEach(function (st) {
		var specs = st[2].map(function (sp) { return sp === null ? 'false' : '{' + sp.join(', ') + '}'; });
		out.push('\t\t{ground = "' + st[0] + '", w = ' + st[1] + ', specs = {' + specs.join(', ') + '}, digest = "' +
			treeDigest(G.rootStudy(st[0] === 'bumpy' ? bumpy(st[3]) : flatGround, st[1],
				st[2].map(function (sp) { return sp === null ? undefined : sp; }))) + '", bumpy_seed = ' + st[3] + '},');
	});
	out.push('\t},');
	out.push('\tfull = {');
	FULL.forEach(function (f) {
		var tree = G.generate(f[0], f[1], f[2] === 'bumpy' ? bumpy(f[1]) : undefined);
		out.push('\t\t{species = "' + f[0] + '", seed = ' + f[1] + ', ground = "' + f[2] + '", text = [[');
		out.push(serialise(tree) + ']]},');
	});
	out.push('\t},');
	out.push('}');
	return out.join('\n') + '\n';
}

var text = build();
if (process.argv[2] === '--check') {
	var old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
	if (old !== text) { console.log('STALE ' + path.relative(REPO, OUT) + ': run node tools/r47_tb/write_reference.js'); process.exit(1); }
	console.log('PASS ' + path.relative(REPO, OUT) + ' is current');
} else {
	fs.writeFileSync(OUT, text);
	console.log('wrote ' + path.relative(REPO, OUT) + ' (' + SEEDS.length + ' seeds x ' + G.ORDER.length +
		' species, bumpy ground for ' + ROOTED.join(', ') + ', ' + FULL.length + ' full lists, ' + text.length + ' bytes)');
}
