#!/usr/bin/env python3
"""Turn the wreck shape files into the mapgen's schematic data (Round 51 lane
WRECK, build step).

    python3 -I tools/r51_wreck/to_lua.py           # write wp40/wreck_shapes.lua
    python3 -I tools/r51_wreck/to_lua.py --check   # fail if it is stale

A mechanical conversion of tools/r51_wreck/shapes/{hull,bow,stern,debris}.json
(schema grug_r51_wreck_shape_v1, DESIGN.md "Shape files"): per shape its key,
size, `seabed` (the layers in the sand) and every occupied cell as five
numbers x, y, z (0-based in the shape's grid; x along the ship, y up from
the bottom layer, z across), the node's index in the shared `names` list
and its param2. "." cells (keep the world's water or sand) are left out.
The writer (wp40/wreck_writer.lua) turns the cells in quarter steps.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "mods", "MAPGEN", "grug_mapgen", "wp40", "wreck_shapes.lua")
ORDER = ("hull", "bow", "stern", "debris")


def convert():
    shapes = []
    for name in ORDER:
        with open(os.path.join(HERE, "shapes", name + ".json"), encoding="utf-8") as handle:
            shapes.append(json.load(handle))
    names = sorted({p["name"] for s in shapes for p in s["palette"].values()})
    lines = [
        "-- Generated by tools/r51_wreck/to_lua.py from tools/r51_wreck/shapes/*.json",
        "-- (Round 51 lane WRECK). Do not edit: change shapes.py, rerun both tools.",
        "-- cells: x, y, z (0-based; x along the ship, y up, z across), node index",
        "-- into `names`, param2; repeated per cell. `seabed`: layers in the sand.",
        "return {",
        "\tnames = {" + ", ".join('"%s"' % n for n in names) + "},",
        "\tshapes = {",
    ]
    for s in shapes:
        cells = []
        for y, rows in enumerate(s["layers"]):
            for z, row in enumerate(rows):
                for x, ch in enumerate(row):
                    if ch == ".":
                        continue
                    p = s["palette"][ch]
                    cells.extend([x, y, z, names.index(p["name"]) + 1, p["param2"]])
        size = s["size"]
        lines.append("\t\t{key = \"%s\", size = {x = %d, y = %d, z = %d}, seabed = %d, cells = {"
                     % (s["key"], size["x"], size["y"], size["z"], s["seabed"]))
        for i in range(0, len(cells), 40):
            lines.append("\t\t\t" + ", ".join(str(v) for v in cells[i:i + 40]) + ",")
        lines.append("\t\t}},")
    lines += ["\t},", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = convert()
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            print("wreck_shapes.lua is stale: run to_lua.py")
            return 1
        print("wreck_shapes.lua is current")
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("wrote", os.path.relpath(OUT, ROOT), len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
