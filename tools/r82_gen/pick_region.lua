-- Round 82 lane BASE: pick the engine region of tools/r82_gen/region.sh on
-- seed 12345 (once; the result is committed as region.txt).
--
--   luajit tools/r82_gen/pick_region.lua REPO > tools/r82_gen/region.txt
--
-- Six patches of 3 x 3 chunk columns (240 x 240 nodes each), centred on: a
-- coast (the first land on the diagonal from the south-west corner, as the
-- seed fleet's sample finds it), the highest ground (a 128-node grid), the
-- middle of the longest main river, the middle of the longest road, the
-- first village's anchor, and just outside the first start's prepared pad
-- (east; the pad itself is generated by the world preparation). Each column
-- runs from the chunk under its lowest ground (or water surface) to the
-- chunk over its highest, generated bottom-up, patch by patch, row by row.
-- Prints "x y z label" per chunk (minp) and, as comments, what each patch
-- holds; refuses overlapping patches.
local repo = assert(arg[1], "usage: pick_region.lua REPO")
local SEED = "12345"
local R = dofile(repo .. "/tools/seed_fleet/runtime.lua")(repo, SEED)
local SOURCE = dofile(repo .. "/mods/MAPGEN/grug_mapgen/wp40/source/simple_map.lua")
local WORLD = SOURCE.world_bounds
local source = R.planner_source
local origin = R.origin

local centres = {}
-- the coast
for step = 8, WORLD.max_x, 8 do
	local x = -(WORLD.max_x - step)
	local z = -math.floor(WORLD.max_z - step * WORLD.max_z / WORLD.max_x)
	if source.column_values_at(x, z) == "land" then
		centres[#centres + 1] = {"coast", x, z}
		break
	end
end
-- the highest ground
do
	local best_x, best_z, best_y = nil, nil, -math.huge
	for x = WORLD.min_x + 256, WORLD.max_x - 256, 128 do
		for z = WORLD.min_z + 256, WORLD.max_z - 256, 128 do
			local water_class, _, _, _, _, terrain_y = source.column_values_at(x, z)
			if water_class == "land" and terrain_y > best_y then
				best_x, best_z, best_y = x, z, terrain_y
			end
		end
	end
	centres[#centres + 1] = {"mountain", best_x, best_z}
end
-- the longest main river and road
do
	local dir = repo .. "/mods/MAPGEN/grug_mapgen/wp40"
	local module = dofile(dir .. "/water_layout.lua")(dofile(dir .. "/terrain_data.lua").water)
	local best
	for _, r in ipairs(module.deserialize(R.main.water_layout_text()).rivers) do
		if not r.parent and (not best or #r.x > #best.x) then best = r end
	end
	local middle = math.floor((#best.x + 1) / 2)
	centres[#centres + 1] = {"river " .. best.id, best.x[middle], best.z[middle]}
	local road
	for _, line in ipairs(R.main.road_polylines()) do
		if line.kind == "road" and (not road or #line.points > #road.points) then road = line end
	end
	local point = road.points[math.floor((#road.points + 1) / 2)]
	centres[#centres + 1] = {"road", point.x, point.z}
end
-- the first village and the first start
do
	local village, start
	for _, row in ipairs(R.main.settlement_sockets(R.built)) do
		if not village and row.slot:find("^village") then village = row end
		if not start and row.slot == "start" then start = row end
	end
	centres[#centres + 1] = {"village " .. village.key, village.anchor.x, village.anchor.z}
	-- the patch's west edge a full chunk past the pad (half width 80) and
	-- its chunk column
	centres[#centres + 1] = {"start edge " .. start.key, start.anchor.x + 80 + 80 + 160,
		start.anchor.z}
end

local patches, lines = {}, {}
for _, c in ipairs(centres) do
	local x0, z0 = origin(c[2]) - 80, origin(c[3]) - 80
	for _, p in ipairs(patches) do
		if math.abs(p.x0 - x0) < 240 and math.abs(p.z0 - z0) < 240 then
			error(c[1] .. " overlaps " .. p.label)
		end
	end
	patches[#patches + 1] = {label = c[1], x0 = x0, z0 = z0}
	local n = {land = 0, river = 0, road = 0, settlement = 0, forest = 0}
	local low, high, chunks = math.huge, -math.huge, 0
	local column_lines = {}
	for dz = 0, 2 do
		for dx = 0, 2 do
			local cx, cz = x0 + dx * 80, z0 + dz * 80
			local lo, hi = math.huge, -math.huge
			for z = cz, cz + 79 do
				for x = cx, cx + 79 do
					local water_class, _, _, biome, _, terrain_y, water_y, river_id, _, functional =
						source.column_values_at(x, z)
					local top = math.max(terrain_y, water_y or 1, 1)
					if terrain_y < lo then lo = terrain_y end
					if top > hi then hi = top end
					if water_class == "land" then n.land = n.land + 1 end
					if river_id ~= nil then n.river = n.river + 1 end
					if source.road_column_at(x, z) ~= nil then n.road = n.road + 1 end
					if functional ~= nil then n.settlement = n.settlement + 1 end
					if type(biome) == "string" and (biome:find("forest", 1, true) or
							biome:find("jungle", 1, true)) then
						n.forest = n.forest + 1
					end
				end
			end
			if lo < low then low = lo end
			if hi > high then high = hi end
			for y = origin(math.min(lo, 1)) - 80, origin(hi) + 80, 80 do
				column_lines[#column_lines + 1] = ("%d %d %d %s"):format(cx, y, cz, c[1])
				chunks = chunks + 1
			end
		end
	end
	lines[#lines + 1] = ("# %s: x %d..%d z %d..%d, ground %d..%d, %d chunks; of 57600 " ..
		"columns land %d, river %d, road %d, settlement %d, forest %d"):format(c[1], x0,
		x0 + 239, z0, z0 + 239, low, high, chunks, n.land, n.river, n.road, n.settlement,
		n.forest)
	for _, line in ipairs(column_lines) do lines[#lines + 1] = line end
end
print("# Round 82 engine region (tools/r82_gen/pick_region.lua), seed " .. SEED ..
	": minp x y z, patch label")
print(table.concat(lines, "\n"))
