def colours(ramp):
    return [ImageColor.getcolor("#" + value, "RGBA") for value in ramp.split()]


def palette(variant, tier):
    metal = colours(METAL_RAMPS[variant][tier - 1])
    gem = colours(GEM_RAMPS[variant][tier - 1])
    trim = metal[1:4]
    if tier == 3:
        trim = colours(COPPER[variant])
    elif tier in (5, 6):
        trim = colours(METAL_RAMPS[variant][3])[1:4]
    p = dict(zip("osmlh", metal))
    p.update(zip("d g c b w".split(), gem))
    p.update(zip("tuv", trim))
    p["p"] = colours(GEM_RAMPS[variant][3])[3] if tier >= 5 else metal[3]
    p["q"] = colours(GEM_RAMPS[variant][4])[2] if tier == 6 else p["p"]
    p["."] = (0, 0, 0, 0)
    return p


def icon(variant, key, tier):
    rows = PIXELS[variant][key].strip().splitlines()
    assert len(rows) == 16 and all(len(row) == 16 for row in rows), (variant, key)
    p = palette(variant, tier)
    im = Image.new("RGBA", (16, 16))
    im.putdata([p[pixel] for row in rows for pixel in row])
    return im


