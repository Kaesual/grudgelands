def png_bytes(im):
    out = BytesIO()
    im.save(out, format="PNG", optimize=False, compress_level=9)
    return out.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    source = (ROOT / "mods/ITEMS/grug_gear/trinkets.lua").read_text()
    assert tuple(re.findall(r'\{key = "([a-z_]+)"', source)) == KEYS, "identity roster changed"
    assert set(PICKS) == set(KEYS), "every identity needs a pick"
    hashes = set()
    outputs = {}
    shipped = {}
    for variant in "ABC":
        sprites = {(key, tier): icon(variant, key, tier)
                   for key in KEYS for tier in range(1, 7)}
        for (key, tier), im in sprites.items():
            name = f"grug_gear_trinket_{key}_t{tier}.png"
            assert im.size == (16, 16) and im.mode == "RGBA", name
            assert set(im.getchannel("A").tobytes()) == {0, 255}, name
            digest = hashlib.sha256(im.tobytes()).hexdigest()
            assert digest not in hashes, "duplicate icon: " + variant + " " + name
            hashes.add(digest)
            if PICKS[key] == variant:
                shipped[(key, tier)] = im
                outputs[TEXTURES / name] = im
        # Only the comparison sheet stays per proposal; the unpicked icons
        # are not kept as files (this generator reproduces them).
        outputs[HERE / "variants" / variant / "sheet.png"] = sheet(variant, sprites)
    outputs[HERE / "final_sheet.png"] = final_sheet(shipped)
    if args.check:
        for variant in "ABC":
            folder = HERE / "variants" / variant
            assert {p.name for p in folder.glob("*.png")} == {"sheet.png"}, folder
        on_disk = {p for p in TEXTURES.glob("grug_gear_trinket_*.png")}
        assert on_disk == {p for p in outputs if p.parent == TEXTURES}, \
            "trinket texture roster differs"
    for path, im in outputs.items():
        data = png_bytes(im)
        if args.check:
            assert path.read_bytes() == data, "stale output: " + str(path)
            with Image.open(path) as saved:
                assert saved.mode == im.mode and saved.size == im.size, path
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Wrote'} {len(outputs)} PNGs: "
          f"{len(shipped)} shipped trinket icons (16x16 RGBA, binary alpha, "
          "picked from 108 unique proposals); 3 proposal sheets; the final sheet.")


