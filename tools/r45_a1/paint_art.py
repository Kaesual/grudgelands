def text(im, xy, value, colour="#d9dedb", scale=2):
    draw = ImageDraw.Draw(im)
    x, y = xy
    for char in value:
        if char != " ":
            for j, row in enumerate(GLYPHS[char].split("/")):
                for i, bit in enumerate(row):
                    if bit == "1":
                        draw.rectangle((x + i * scale, y + j * scale,
                                        x + (i + 1) * scale - 1,
                                        y + (j + 1) * scale - 1), fill=colour)
        x += 4 * scale


def centre(im, x, y, value, colour="#d9dedb", scale=2):
    text(im, (x - (len(value) * 4 - 1) * scale // 2, y), value, colour, scale)


def sample(im, sprite, xy, scale=4):
    im.alpha_composite(sprite.resize((16 * scale, 16 * scale), NEAREST), xy)


