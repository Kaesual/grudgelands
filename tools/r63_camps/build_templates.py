#!/usr/bin/env python3
"""Freeze the user-approved camp composition into ordinary game templates.

The accepted visual recipe is tools/mining_camp_review/build.py. Material
roles remain roles; the headframe is read from each current capital template.
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools/mining_camp_review'))
import build as review
sys.path.insert(0, str(ROOT/'tools/building_templates/editor'))
import tplfile

OUT = ROOT/'mods/MAPGEN/grug_mapgen/building_templates/templates'


def entry(value):
    name,p2 = value
    if name.startswith('proposal:'):
        short = name.split(':',1)[1]
        name = 'grug_mapgen:' + ('faction_'+short if short.startswith('banner_') else 'camp_'+short)
    if name.startswith('role ') or name.startswith('node '):
        # Headframe legend entries already carry their authored orientation.
        return name
    kind = 'wallmounted' if name in ('default:ladder_wood', 'default:torch') else 'facedir'
    return 'node '+name+((' o='+kind+':'+str(p2)) if p2 else '')


def model(race, capital, faction, large):
    source=review.T.parse_template(str(OUT/(capital.lower().replace(' ','_')+'_miners_guild.tpl')))
    # The headframe uses plain roles/fixed nodes, with no race switches.
    hall={pos:(source.legend[key]['text'],0) for pos,key in source.cells.items()
          if key not in (review.T.FORCE_AIR,review.T.UNCHANGED)}
    palette=review.G.load_palettes(review.V.find_lua(),['air'])['races'][race]
    symbolic={'race':race,'roles':{role:'role '+role for role in palette}}
    kind='pvp_camp_high' if large else 'mining_camp'
    cells,points=review.proposal(symbolic,hall,faction,kind)
    # Travel checks whole nodes for solid collision: keep the return deck open.
    cells.pop((-1,1,6),None)
    cells[(-1,0,6)]=('role floor',0)
    # Retain param2 on role cells; fixed headframe entries already encode it.
    converted={}
    for pos,(name,p2) in cells.items():
        e=entry((name,p2))
        if name.startswith('role ') and p2:
            e += ' o=facedir:'+str(p2)
        converted[pos]=e
    r=13 if large else 11
    points.update(gate_west=[-2,1,-r+2],gate_east=[2,1,-r+2],
                  yard_west=[-4,1,0],yard_east=[4,1,0],captain=[0,1,4])
    if large:
        points.update(tower_west=[-10,1,-7],tower_east=[10,1,-7],yard_west=[-4,1,1])
    name='mining_camp_'+race+('_large' if large else '')
    m=tplfile.Model()
    m.name,m.cell=name,1
    m.origin,m.size,m.pivot=(-r,0,-r),(2*r+1,17,2*r+1),(2*r+1,2*r+1)
    m.races=[race]
    m.head=[
        '# Round 63: approved camp; generated by tools/r63_camps/build_templates.py.',
        'name '+name, f'pivot {2*r+1} {2*r+1}',f'origin {-r} 0 {-r}',
        f'size {2*r+1} 17 {2*r+1}', 'cell 1',
        f'meta extent=[{-r},{-r},{r},{r}] peak=16 top=16','races '+race]
    entries=sorted(set(converted.values()))
    assert len(entries)<=len(tplfile.ALPHABET)
    key_of={e:tplfile.ALPHABET[i] for i,e in enumerate(entries)}
    m.legend=[[key_of[e],e] for e in entries]
    for y in range(17):
        m.layers.append([''.join(key_of.get(converted.get((x,y,z)),'.')
                                 for x in range(-r,r+1)) for z in range(-r,r+1)])
    # These are placement markers. The blueprint owns which actors/roles
    # apply to a mining camp, a contested camp or a Battlegrounds camp.
    for key,pos in sorted(points.items()):
        m.points.append(['camp_points',*pos,'id='+key])
    m.points.append(['doors',0,1,-r,'face=0 id=gate'])
    m.points.append(['inside',0,1,0,'id=yard'])
    return name,tplfile.dump(m)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    for faction,races in review.RACES.items():
        for race,capital in races:
            for large in (False,True):
                name,text=model(race,capital,faction,large)
                path=OUT/(name+'.tpl')
                if args.check:
                    assert path.read_text()==text, 'template differs: '+str(path)
                else:
                    path.write_text(text)
    print('Round 63: 12 camp templates '+('verified' if args.check else 'written'))

if __name__=='__main__':main()
