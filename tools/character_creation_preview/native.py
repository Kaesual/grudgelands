#!/usr/bin/env python3
"""Build a separate native-camera scene series; preserve the browser proposal.

Run native.py, render-scenes.mjs --directory <absolute native folder>, then
native.py --install. The native viewport has the same 11:10 image aspect at every
window size. Model height is a fraction of that viewport, times race stature.
"""
import hashlib
import json
import math
from pathlib import Path
import re
import shutil
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / 'native'
sys.path.insert(0, str(ROOT / 'tools/r33_c3'))
import gen_cloak_model as mesh


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build(source=HERE, output=OUT, write_camera=True):
    source, output = Path(source), Path(output)
    data = mesh.SOURCE.read_bytes()
    bounds = mesh.stand_bounds(mesh.parse(data, 0, len(data)))
    width, height, depth = [bounds[i + 3] - bounds[i] for i in range(3)]
    config = {'height_fraction': .60, 'aspect': .8, 'pitch': 12,
              'image_width': 1540, 'image_height': 1400, 'mesh_bounds': bounds, 'mesh_hash': sha(data)}
    assert config['aspect'] > max(width, depth) / height, 'native camera must fit vertically'
    distance = height / (2 * math.tan(math.radians(15))) + max(width, depth) / 2
    page = (source / 'scenes.html').read_text()
    pattern = r'(<script id="payload" type="application/json">)(.*?)(</script>)'
    payload = json.loads(re.search(pattern, page, re.S)[2])
    receipts = {}
    (output / 'scenes').mkdir(parents=True, exist_ok=True)
    for race, scene in payload['scenes'].items():
        spec = scene['spec']
        stature = spec['portrait']['stature']
        x, y, z = spec['portrait']['feet']
        target = [x, y + (bounds[1] + bounds[4]) * .05 * stature, z]
        distance_world = distance * .1 * stature
        pitch = math.radians(config['pitch'])
        spec['camera'] = {
            'eye': [x, target[1] + math.sin(pitch) * distance_world,
                    z - math.cos(pitch) * distance_world],
            'target': target,
            'fov': math.degrees(2 * math.atan(math.tan(math.radians(15)) /
                                            (config['height_fraction'] * stature))),
        }
        scene['digest'] = sha(json.dumps({'source': scene['digest'], 'spec': spec,
                                          'config': config, 'builder': sha(Path(__file__).read_bytes())},
                                         sort_keys=True).encode())
        receipts[race] = {'render_input': scene['digest'], 'camera': spec['camera']}
        (output / 'scenes' / (race + '.json')).write_text(json.dumps(spec, indent=2) + '\n')
    encoded = json.dumps(payload, separators=(',', ':')).replace('</', '<\\/')
    page = re.sub(pattern, lambda m: m[1] + encoded + m[3], page, flags=re.S)
    (output / 'scenes.html').write_text(page)
    (output / 'calibration.json').write_text(json.dumps(config, indent=2) + '\n')
    (output / 'scene-build.json').write_text(json.dumps(receipts, indent=2) + '\n')
    lua = ('-- Generated by tools/character_creation_preview/native.py.\n'
           '-- GUIScene: 30-degree vertical FOV, bounding-box auto-fit.\n'
           'return {height_fraction = %.8f, aspect = %.8f, pitch = %.8f, scene_aspect = 1.1}\n') % (
               config['height_fraction'], config['aspect'], config['pitch'])
    if write_camera:
        (ROOT / 'mods/PLAYER/grug_classes/creation_camera.lua').write_text(lua)
    print('Native camera scenes ready:', output)


def install():
    receipts = json.loads((OUT / 'scene-build.json').read_text())
    for race, source in receipts.items():
        path = OUT / 'renders' / (race + '.png')
        receipt = json.loads(path.with_suffix('.json').read_text())
        assert receipt['input'] == source['render_input'] and receipt['output'] == sha(path.read_bytes()), race
        assert receipt['width'] == 1540 and receipt['height'] == 1400
        shutil.copyfile(path, ROOT / 'mods/PLAYER/grug_classes/textures' / ('grug_creation_' + race + '.png'))
    print('Installed six native backdrop PNGs; browser proposal unchanged.')


if __name__ == '__main__':
    if '--install' in sys.argv:
        install()
    else:
        build()
