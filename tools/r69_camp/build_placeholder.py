#!/usr/bin/env python3
"""Round 69 lane CAMP: the placeholder camp site templates.

Writes `camp_site_<race>.tpl` for the six races: the camp under construction
of Round 58 redrawn in the Round 63 materials (stockade panels, canvas,
faction trim), so the migration can be proved before the user's picked design
replaces these files (lane CAMPART, phase 2). The frame is the design's
contract: 23 x 10 x 23, origin -11 0 -11, every cell written, the sockets on
their Round 58 cells.

Usage: python3 tools/r69_camp/build_placeholder.py [--check]
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/building_templates/editor'))
import tplfile  # noqa: E402

OUT = ROOT / 'mods/MAPGEN/grug_mapgen/building_templates/templates'
R, TOP = 11, 9
FACTION = {'dwarf': 'accord', 'human': 'accord', 'elf': 'accord',
           'undead': 'throng', 'orc': 'throng', 'troll': 'throng'}
SOCKETS = {'gate_west': (-2, 1, -9), 'gate_east': (2, 1, -9), 'yard_west': (-4, 1, 1),
           'yard_east': (4, 1, 1), 'captain': (0, 1, 3)}
LANTERN = 'node grug_decor:xdecor_lantern'


def composition(race):
    """cells: (x, y, z) -> legend entry; everything else in the box is air."""
    wall = 'node grug_mapgen:camp_stockade_' + race
    canvas, ridge = 'node grug_mapgen:camp_canvas', 'node grug_mapgen:camp_ridge'
    trim = 'node grug_mapgen:camp_trim_' + FACTION[race]
    cells = {}

    def fill(x1, y1, z1, x2, y2, z2, entry):
        for z in range(z1, z2 + 1):
            for y in range(y1, y2 + 1):
                for x in range(x1, x2 + 1):
                    cells[(x, y, z)] = entry

    def lamp(x, z, top):
        fill(x, 1, z, x, top, z, 'role post')
        cells[(x, top + 1, z)] = LANTERN

    fill(-R, 0, -R, R, 0, R, 'role ground')
    # Trampled ground from the gate to the command tent.
    fill(-1, 0, -R, 1, 0, 3, 'role rubble')
    # The stockade begun on the gate side and stopped halfway along the flanks.
    for x in range(-R, R + 1):
        if abs(x) > 1:
            fill(x, 1, -R, x, 1 + (x * 3 - R) % 3, -R, wall)
    for z in range(-R + 1, 1):
        for x in (-R, R):
            fill(x, 1, z, x, 1 + (x * 3 + z) % 3, z, wall + ' o=facedir:1')
    lamp(-2, -R, 3)
    lamp(2, -R, 3)
    # A scaffolded watchtower: four corner posts and a plank deck.
    for x in (-8, -6):
        for z in (-8, -6):
            fill(x, 1, z, x, 6, z, 'role post')
    fill(-8, 4, -8, -6, 4, -6, 'role floor')
    # A hut frame: corner posts and the first beams.
    for x, z in ((5, -8), (9, -8), (5, -4), (9, -4)):
        fill(x, 1, z, x, 3, z, 'role post')
    fill(6, 3, -8, 8, 3, -8, 'role beam')
    fill(5, 3, -7, 5, 3, -5, 'role beam')
    # Timber and supplies.
    fill(5, 1, 5, 7, 1, 6, 'role beam')
    fill(5, 1, 8, 7, 2, 9, 'role beam')
    fill(-9, 1, 7, -7, 1, 8, 'role storage')
    fill(-9, 1, 1, -8, 1, 2, 'role rubble')
    # The command tent, open towards the captain.
    half = 3
    for z in range(4, 9):
        for dx in range(-half, half + 1):
            entry = trim if abs(dx) == half else canvas
            cells[(dx, half + 1 - abs(dx), z)] = entry
        cells[(0, half + 2, z)] = ridge
    for dx in range(-half + 1, half):
        fill(dx, 1, 8, dx, half - abs(dx), 8, canvas)
    fill(-2, 0, 5, 2, 0, 7, 'role floor')
    lamp(-4, 3, 2)
    lamp(4, -3, 2)
    return cells


def model(race):
    cells = composition(race)
    name = 'camp_site_' + race
    m = tplfile.Model()
    m.name, m.cell = name, 1
    side = 2 * R + 1
    m.origin, m.size, m.pivot = (-R, 0, -R), (side, TOP + 1, side), (side, side)
    m.races = [race]
    m.head = ['# Round 69: placeholder until the user\'s pick; '
              'generated by tools/r69_camp/build_placeholder.py.',
              'name ' + name, 'pivot %d %d' % (side, side), 'origin %d 0 %d' % (-R, -R),
              'size %d %d %d' % (side, TOP + 1, side), 'cell 1',
              'meta extent=[%d,%d,%d,%d] peak=%d top=%d' % (-R, -R, R, R, TOP, TOP),
              'races ' + race]
    entries = sorted(set(cells.values()))
    key_of = {e: tplfile.ALPHABET[i] for i, e in enumerate(entries)}
    m.legend = [[key_of[e], e] for e in entries]
    for y in range(TOP + 1):
        m.layers.append([''.join(key_of[cells[(x, y, z)]] if (x, y, z) in cells else '.'
                                 for x in range(-R, R + 1)) for z in range(-R, R + 1)])
    for key, pos in sorted(SOCKETS.items()):
        m.points.append(['camp_points', *pos, 'id=' + key])
    m.points.append(['doors', 0, 1, -R, 'face=0 id=gate'])
    m.points.append(['inside', 0, 1, 0, 'id=yard'])
    return name, tplfile.dump(m)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for race in FACTION:
        name, text = model(race)
        path = OUT / (name + '.tpl')
        if args.check:
            assert path.read_text() == text, 'template differs: ' + str(path)
        else:
            path.write_text(text)
    print('Round 69: 6 camp site templates ' + ('verified' if args.check else 'written'))


if __name__ == '__main__':
    main()
