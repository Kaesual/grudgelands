#!/usr/bin/env python3
"""Round 51 lane LK: the land kit's prop nodes from ARTL's props.

Reads every prop of tools/r51_land/props (the prop format of
tools/r51_land/README.md) and writes

  mods/ITEMS/grug_nodes/props_data.lua   one row per prop: node name, name,
                                         drop, tiles (+Y -Y +X -X +Z -Z),
                                         boxes in sixteenths, alpha, rotate
  mods/ITEMS/grug_nodes/textures/grug_nodes_<prop>_<face>.png
                                         the prop's six tiles, byte for byte

`bones_scattered` is the bone pile's successor (land plan ruling 9): it is
registered as `grug_nodes:bone_pile` and its tiles are named after that
node. `gravestone_slab` becomes `grug_nodes:gravestone_stele` (a name
ending in `_slab` reads as a stair slab to grug_decor's slab placement). grug_nodes/props.lua turns the rows into nodes (box values / 16).

  python3 -I tools/r51_lk/gen_props.py           write
  python3 -I tools/r51_lk/gen_props.py --check   fail if anything is stale
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROPS = os.path.join(REPO, "tools", "r51_land", "props")
MOD = os.path.join(REPO, "mods", "ITEMS", "grug_nodes")
DATA = os.path.join(MOD, "props_data.lua")
TEXTURES = os.path.join(MOD, "textures")
# The prop folder whose node keeps an existing name.
NODE_NAME = {"bones_scattered": "bone_pile", "gravestone_slab": "gravestone_stele"}
FACES = ("top", "bottom", "right", "left", "back", "front")


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    rows = []
    for prop in sorted(os.listdir(PROPS)):
        path = os.path.join(PROPS, prop, "prop.json")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as handle:
            spec = json.load(handle)
        node = NODE_NAME.get(prop, prop)
        tiles = spec["tiles"]
        if len(tiles) != 6:
            raise SystemExit("%s: six tiles expected" % prop)
        names = []
        for index, tile in enumerate(tiles):
            expected = "%s_%s.png" % (prop, FACES[index])
            if tile != expected:
                raise SystemExit("%s: tile %d is %s, expected %s" % (prop, index + 1, tile, expected))
            names.append("grug_nodes_%s_%s.png" % (node, FACES[index]))
        for box in spec["boxes"]:
            if len(box) != 6 or any(not isinstance(v, int) or v < -8 or v > 8 for v in box) or \
                    box[0] >= box[3] or box[1] >= box[4] or box[2] >= box[5]:
                raise SystemExit("%s: box %r out of the format" % (prop, box))
        rows.append({"prop": prop, "node": "grug_nodes:" + node, "name": spec["name"],
                     "drop": spec["drop"], "tiles": names, "sources": tiles,
                     "boxes": spec["boxes"], "alpha": spec.get("alpha") == "clip",
                     "rotate": spec.get("rotate", True) is not False})
    return rows


def render(rows):
    out = [
        "-- GENERATED by tools/r51_lk/gen_props.py from tools/r51_land/props (Round 51",
        "-- lane LK); do not edit. One row per prop: the node, its name, what digging",
        "-- it gives (\"\" nothing), its tiles (+Y -Y +X -X +Z -Z), its boxes in",
        "-- sixteenths, whether transparent pixels cut holes (alpha clip) and whether",
        "-- it may stand turned (facedir). props.lua registers them.",
        "return {",
    ]
    for row in rows:
        out.append("\t{prop = %s, node = %s," % (lua_string(row["prop"]), lua_string(row["node"])))
        out.append("\t\tname = %s, drop = %s," % (lua_string(row["name"]), lua_string(row["drop"])))
        out.append("\t\ttiles = {%s}," % ", ".join(lua_string(t) for t in row["tiles"]))
        out.append("\t\tboxes = {")
        for box in row["boxes"]:
            out.append("\t\t\t{%s}," % ", ".join(str(v) for v in box))
        out.append("\t\t},")
        out.append("\t\talpha = %s, rotate = %s}," % ("true" if row["alpha"] else "false",
                                                      "true" if row["rotate"] else "false"))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    rows = load()
    stale = []
    text = render(rows)
    current = open(DATA, encoding="utf-8").read() if os.path.exists(DATA) else None
    if current != text:
        stale.append(DATA)
        if not check:
            with open(DATA, "w", encoding="utf-8") as handle:
                handle.write(text)
    for row in rows:
        for source, target in zip(row["sources"], row["tiles"]):
            with open(os.path.join(PROPS, row["prop"], source), "rb") as handle:
                data = handle.read()
            path = os.path.join(TEXTURES, target)
            if not os.path.exists(path) or open(path, "rb").read() != data:
                stale.append(path)
                if not check:
                    with open(path, "wb") as handle:
                        handle.write(data)
    if check and stale:
        for path in stale:
            print("stale: " + os.path.relpath(path, REPO))
        raise SystemExit(1)
    print("%d props, %s" % (len(rows), "up to date" if not stale else "%d files written" % len(stale)))


if __name__ == "__main__":
    main()
