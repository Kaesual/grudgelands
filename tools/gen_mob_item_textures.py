#!/usr/bin/env python3
"""Generates the 16x16 mob-material item icons of grug_mobs (plus the few
node tiles of other mods that are authored the same way).

Grudgelands project, **CC0 1.0** - original pixel art, NOT derived from any
vendored or third-party asset. Fully deterministic (no randomness), so
re-running the script reproduces every PNG byte-for-byte.

Every icon is authored as a 16x16 ASCII map plus a per-icon palette, which
makes the art reviewable in the diff instead of only in a binary blob.

Usage:
    python3 tools/gen_mob_item_textures.py [outdir [nodes_outdir]]

Default outdir:       mods/ENTITIES/grug_mobs/textures  (ICONS)
Default nodes_outdir: mods/ITEMS/grug_nodes/textures    (NODE_ICONS)
"""

import os
import sys

from PIL import Image

TRANSPARENT = (0, 0, 0, 0)


def rgba(hexstr):
    hexstr = hexstr.lstrip("#")
    return (int(hexstr[0:2], 16), int(hexstr[2:4], 16), int(hexstr[4:6], 16), 255)


def build(name, art, palette, outdir):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16, "%s: %d rows" % (name, len(rows))
    img = Image.new("RGBA", (16, 16), TRANSPARENT)
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == 16, "%s: row %d has %d cols" % (name, y, len(row))
        for x, ch in enumerate(row):
            if ch != ".":
                assert ch in palette, "%s: unmapped char %r" % (name, ch)
                px[x, y] = rgba(palette[ch])
    path = os.path.join(outdir, name)
    img.save(path)
    return path


