#!/usr/bin/env python3
"""The armor atlas: one deterministic packing of every catalog box sheet.

Every box of data/catalog.json gets one rectangle of its sheet size (one per
shape; a mirrored left copy shares the right copy's sheet). The model's UVs
(MODEL), the baked atlas layers (BAKE) and the game's composition (GAME) all
read data/atlas.json, so a sheet painted for a box lands where that box's
faces sample it.

Packing: shelves left to right, boxes sorted by sheet height, then width
(both descending), then id; no gutter (like the 64x32 skin). The atlas is
ATLAS_W x ATLAS_H texels, origin top left. The polygon parts (Round 56, spec
section 1a) come after the boxes, so every box keeps its place: their sheets
whole, from the left edge of the first row below the boxes, left to right in
catalog order (a new shelf when a row is full), under the key `parts`; the
space below is free for later parts.

  python3 atlas.py            write data/atlas.json
  python3 atlas.py --check    exit 1 if data/atlas.json is stale or invalid
  python3 atlas.py --png OUT  draw the layout at 4x with labels
"""
import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
TOOL = Path(__file__).resolve().parent
DATA = TOOL / "data"
ATLAS_W, ATLAS_H = 128, 64


def pack(cat):
    boxes = sorted(cat["boxes"], key=lambda b: (-b["sheet"][1], -b["sheet"][0], b["id"]))
    x = y = shelf = 0
    out = {}
    for b in boxes:
        w, h = b["sheet"]
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf, 0
        out[b["id"]] = {
            "rect": [x, y, w, h],
            "faces": {f: [x + fx, y + fy, fw, fh] for f, (fx, fy, fw, fh) in b["faces"].items()},
        }
        x += w
        shelf = max(shelf, h)
    # the polygon parts: their sheets whole, below the boxes, in catalog order
    x, y, shelf = 0, max(e["rect"][1] + e["rect"][3] for e in out.values()), 0
    parts = {}
    for p in cat.get("parts", []):
        w, h = p["sheet"]
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf, 0
        parts[p["id"]] = {
            "rect": [x, y, w, h],
            "faces": {f: [x + fx, y + fy, fw, fh] for f, (fx, fy, fw, fh) in p["faces"].items()},
        }
        x += w
        shelf = max(shelf, h)
    return {
        "_doc": "Generated by atlas.py from data/catalog.json; spec: docs/technical/armor-format.md section 3. "
                "size = [w, h] texels; per box: rect = [x, y, w, h] of its sheet in the atlas (origin top left), "
                "faces = the six face rectangles in atlas texels. UV u = x / w, v = y / h (top left origin). "
                "parts: the polygon parts (section 1a), rect = the whole sheet, faces = each face's rect; a "
                "model UV is the rect's corner plus the face's uv from the part's schema file.",
        "size": [ATLAS_W, ATLAS_H],
        "boxes": {bid: out[bid] for bid in (b["id"] for b in cat["boxes"])},   # catalog order
        "parts": parts,
    }


def validate(atlas):
    errs = []
    W, H = atlas["size"]
    rects = []
    for bid, e in list(atlas["boxes"].items()) + list(atlas.get("parts", {}).items()):
        x, y, w, h = e["rect"]
        if x < 0 or y < 0 or x + w > W or y + h > H:
            errs.append(f"{bid}: rect {e['rect']} outside the {W}x{H} atlas")
        for f, (fx, fy, fw, fh) in e["faces"].items():
            if fx < x or fy < y or fx + fw > x + w or fy + fh > y + h:
                errs.append(f"{bid} {f}: face rect outside its sheet")
        rects.append((bid, x, y, w, h))
    for i, (a, ax, ay, aw, ah) in enumerate(rects):
        for b, bx, by, bw, bh in rects[i + 1:]:
            if ax < bx + bw and bx < ax + aw and ay < by + bh and by < ay + ah:
                errs.append(f"{a} and {b} overlap")
    return errs


def draw(atlas, cat, path):
    from PIL import Image, ImageDraw
    S = 4
    W, H = atlas["size"]
    im = Image.new("RGB", (W * S, H * S), (40, 40, 46))
    d = ImageDraw.Draw(im)
    shade = {"top": (120, 150, 190), "bottom": (90, 110, 150), "right": (160, 130, 100),
             "front": (200, 180, 120), "left": (150, 120, 90), "back": (130, 160, 120)}
    for bid, e in list(atlas["boxes"].items()) + list(atlas.get("parts", {}).items()):
        for f, (x, y, w, h) in e["faces"].items():
            d.rectangle([x * S, y * S, (x + w) * S - 1, (y + h) * S - 1],
                        fill=shade.get(f, (170, 170, 200)), outline=None if f in shade else (90, 90, 120))
        x, y, w, h = e["rect"]
        d.rectangle([x * S, y * S, (x + w) * S - 1, (y + h) * S - 1], outline=(255, 255, 255))
        d.text((x * S + 2, y * S + 2), bid, fill=(0, 0, 0))
    im.save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if data/atlas.json is stale or invalid")
    ap.add_argument("--png", help="draw the layout to this PNG")
    a = ap.parse_args()
    cat = json.loads((DATA / "catalog.json").read_text())
    atlas = pack(cat)
    errs = validate(atlas)
    path = DATA / "atlas.json"
    text = json.dumps(atlas, indent=1) + "\n"
    if a.check:
        if not path.exists() or path.read_text() != text:
            errs.append(f"{path} is stale: run python3 atlas.py")
        for e in errs:
            print("FAIL", e)
        print("atlas check:", "FAIL" if errs else "ok",
              f"({len(atlas['boxes'])} boxes, {len(atlas['parts'])} polygon parts, {ATLAS_W}x{ATLAS_H})")
        return 1 if errs else 0
    if errs:
        for e in errs:
            print("FAIL", e)
        return 1
    path.write_text(text)
    used = max(e["rect"][1] + e["rect"][3] for e in atlas["boxes"].values())
    print("wrote", path, len(atlas["boxes"]), f"boxes, {ATLAS_W}x{ATLAS_H}, rows 0-{used - 1} used by boxes")
    for pid, e in atlas["parts"].items():
        x, y, w, h = e["rect"]
        print(f"  part {pid}: rect {e['rect']} (rows {y}-{y + h - 1})")
    if a.png:
        draw(atlas, cat, a.png)
        print("wrote", a.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
