#!/usr/bin/env bash
# Build a town-workshop package from one git ref: the game exactly as that
# ref has it, plus a world in which the start town is already generated,
# the dev-only grug_town_workshop world mod is installed and the "baseline"
# export is written. A designer rebuilds the town in that world; its
# `/town_export` then goes to diff_town.py against the same ref's blueprint.
#
# Usage: tools/building_templates/viewer/make_workshop.sh [-r REF] [-t TOWN] [-s SEED] [-o OUTDIR]
#   REF     git ref to build from (default: HEAD of this checkout)
#   TOWN    start-town key (default: dawnmere)
#   SEED    world seed (default: 20261016; keep it, so a verification world
#           built later from a changed blueprint has the same terrain)
#   OUTDIR  where the package directory goes (default: ~/projects/grudgelands-town-workshop)
#
# The ref is checked out into a temporary detached worktree, and the world is
# generated by that worktree's tools/luanti_headless.sh (isolated temp user
# path, random port, killed and cleaned afterwards). Nothing under
# ~/.var/app/org.luanti.luanti is read or written.
set -euo pipefail
export LC_ALL=C
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(git -C "$here" rev-parse --show-toplevel)"
ref=HEAD town=dawnmere seed=20261016 out="$HOME/projects/grudgelands-town-workshop"
while getopts "r:t:s:o:" opt; do
	case $opt in
		r) ref=$OPTARG ;; t) town=$OPTARG ;; s) seed=$OPTARG ;; o) out=$OPTARG ;;
		*) sed -n '2,20p' "$0"; exit 2 ;;
	esac
done
case $town in hearthpine|dawnmere|silverleaf|stillgrave|sunscar|kapok) ;;
	*) echo "unknown town: $town" >&2; exit 2 ;; esac

sha="$(git -C "$repo" rev-parse --verify "$ref^{commit}")"
short="${sha:0:8}"
scratch="$(mktemp -d /tmp/grug-town-workshop.XXXXXX)"
tree="$scratch/tree"
cleanup() {
	git -C "$repo" worktree remove --force "$tree" 2>/dev/null || true
	rm -rf "$scratch"
}
trap cleanup EXIT

git -C "$repo" worktree add --detach --quiet "$tree" "$sha"
version="$(sed -n 's/^version *= *//p' "$tree/game.conf")"
[[ -x "$tree/tools/luanti_headless.sh" ]] || { echo "ref has no tools/luanti_headless.sh" >&2; exit 1; }

# The preparing copy of the world mod: same code, plus prepare.txt.
probe="$scratch/grug_town_workshop"
cp -a "$here/grug_town_workshop" "$probe"
echo "$town" >"$probe/prepare.txt"

echo "building $town workshop from $short (game $version, seed $seed) ..."
run_log="$scratch/run.txt"
(cd "$tree" && KEEP=1 SEED="$seed" PROBE="$probe" timeout 330 tools/luanti_headless.sh 300) \
	>"$run_log" 2>&1 || { cat "$run_log" >&2; exit 1; }
root="$(sed -n 's/^kept: //p' "$run_log")"
[[ -n "$root" && -d "$root/world" ]] || { cat "$run_log" >&2; exit 1; }
trap 'rm -rf "$root"; cleanup' EXIT
grep -q "PREPARE DONE" "$root/server.log" ||
	{ grep -n "town_workshop\|ERROR" "$root/server.log" >&2; exit 1; }
[[ -s "$root/world/town_exports/$town-baseline.tsv" ]] ||
	{ echo "no baseline export written" >&2; exit 1; }

pkg="$out/grudgelands-$version-$short-$town"
rm -rf "$pkg"
mkdir -p "$pkg/games" "$pkg/worlds"
world="$pkg/worlds/$town-workshop"
cp -a "$root/world" "$world"
mkdir -p "$world/worldmods"
cp -a "$here/grug_town_workshop" "$world/worldmods/"
rm -f "$world/worldmods/grug_town_workshop/prepare.txt"
printf 'ref\t%s\nversion\t%s\nseed\t%s\ntown\t%s\n' "$sha" "$version" "$seed" "$town" \
	>"$world/town_workshop_source.txt"
mkdir -p "$pkg/games/grudgelands"
git -C "$repo" archive "$sha" game.conf mods minetest.conf settingtypes.txt menu |
	tar -x -C "$pkg/games/grudgelands"

cat >"$pkg/README.txt" <<EOF
Grudgelands town workshop: $town, game $version ($short), seed $seed

1. Copy games/grudgelands into your Luanti "games" folder (replace an older
   Grudgelands there, or use a separate Luanti install for this), and
   worlds/$town-workshop into your Luanti "worlds" folder.
2. Start Luanti, pick the Grudgelands game and the world "$town-workshop",
   and press Play (singleplayer is enough).
3. The first start finishes generating the world: you may wait in the sky
   for a minute, then create a character (any faction and class).
   On joining you get creative inventory, fly (K),
   fast (J), noclip (H), and protection bypass. Hostile mobs ignore you.
4. Type /town_go $town to fly above the town. Rebuild what you like.
5. When done, type /town_export $town designer
   The file appears in worlds/$town-workshop/town_exports/$town-designer.tsv
   Send that file back (the baseline export is already in the same folder).

Open this world only with the game from this package: an older or newer
Grudgelands may not match the generated town.
EOF
du -sh "$pkg" | sed 's/^/package: /'
echo "$pkg"
