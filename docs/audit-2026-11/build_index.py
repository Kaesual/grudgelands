#!/usr/bin/env python3
"""Builds by-topic/*.md and by-topic/all.md from the finding headings.

Usage: python3 build_index.py   (run from anywhere; paths are relative to
this file). Reads findings/<PKG>.md (verified); a package that only has
raw/<PKG>.md is listed with the verdict UNVERIFIED (raw). Refuted findings
are left out of the tables and counted.
"""
import os
import re
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = re.compile(r"^###\s+([A-Z0-9]+-[A-Z]?\d+)\s*\|\s*(\w+)\s*\|\s*([\w/-]+)\s*\|\s*(.+?)\s*$")
VERDICT = re.compile(r"\*\*Verdict:\*\*\s*([A-Z]+)")
WHERE = re.compile(r"\*\*Where:\*\*\s*(.+)")
EFFORT = re.compile(r"\*\*Effort:\*\*\s*([SML])")
SEV = {"critical": 0, "high": 1, "medium": 2, "low": 3}
TOPICS = [
    ("performance", "Performance", {"perf"}),
    ("duplication", "Duplication", {"dup"}),
    ("dead-code-and-simplification", "Dead code, simplification, structure", {"dead", "simplify", "structure"}),
    ("bugs-and-edge-cases", "Bugs and edge cases", {"bug", "edge"}),
    ("persistence-and-upgrade", "Persistence and upgrade safety", {"persist"}),
    ("security-and-exploits", "Security and exploits", {"security"}),
    ("determinism", "Determinism", {"determinism"}),
    ("docs-drift", "Documentation drift", {"docs"}),
]


def parse(path, default_verdict):
    rows, cur = [], None
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = HEAD.match(line)
            if m:
                cur = {"id": m.group(1), "sev": m.group(2), "cat": m.group(3).lower(),
                       "title": m.group(4), "verdict": default_verdict, "where": "", "effort": "?"}
                rows.append(cur)
                continue
            if line.startswith("#"):
                cur = None if line.startswith("## ") or line.startswith("# ") else cur
                continue
            if cur is None:
                continue
            for rx, key in ((VERDICT, "verdict"), (WHERE, "where"), (EFFORT, "effort")):
                m = rx.search(line)
                if m and (key != "where" or not cur["where"]):
                    cur[key] = m.group(1).strip()
    return rows


def main():
    rows, source = [], {}
    for sub, default in (("findings", "UNVERIFIED"), ("raw", "UNVERIFIED (raw)")):
        d = os.path.join(HERE, sub)
        for name in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            pkg = name[:-3]
            if not name.endswith(".md") or pkg in source:
                continue
            source[pkg] = sub
            for r in parse(os.path.join(d, name), default):
                r["pkg"], r["file"] = pkg, f"../{sub}/{name}"
                rows.append(r)
    refuted = [r for r in rows if r["verdict"].startswith("REFUTED")]
    live = [r for r in rows if not r["verdict"].startswith("REFUTED")]
    live.sort(key=lambda r: (SEV.get(r["sev"].lower(), 9), r["id"]))
    out = os.path.join(HERE, "by-topic")
    os.makedirs(out, exist_ok=True)

    def table(rs):
        lines = ["| Id | Severity | Category | Title | Where | Effort | Verdict |", "|---|---|---|---|---|---|---|"]
        for r in rs:
            where = r["where"].split(" (")[0][:90].replace("|", "/")
            lines.append(f"| [{r['id']}]({r['file']}) | {r['sev']} | {r['cat']} | {r['title'].replace('|', '/')} | {where} | {r['effort']} | {r['verdict']} |")
        return "\n".join(lines) + "\n"

    known = set()
    for slug, title, cats in TOPICS:
        known |= cats
        rs = [r for r in live if r["cat"] in cats]
        with open(os.path.join(out, slug + ".md"), "w", encoding="utf-8") as fh:
            fh.write(f"# {title}\n\nGenerated by `build_index.py`; {len(rs)} findings, most severe first. "
                     "The package files under `findings/` are the authority.\n\n" + table(rs))
    rest = [r for r in live if r["cat"] not in known]
    with open(os.path.join(out, "all.md"), "w", encoding="utf-8") as fh:
        fh.write(f"# All findings\n\nGenerated by `build_index.py`; {len(live)} findings "
                 f"({len(refuted)} refuted ones left out), most severe first.\n\n" + table(live))
        if rest:
            fh.write("\n## Findings with an unknown category\n\n" + table(rest))
    by_pkg = defaultdict(Counter)
    for r in rows:
        by_pkg[r["pkg"]][r["verdict"].split()[0] if not r["verdict"].startswith("UNVERIFIED (raw)") else "RAW"] += 1
        if not r["verdict"].startswith("REFUTED"):
            by_pkg[r["pkg"]]["sev:" + r["sev"]] += 1
    head = ("Package", "Source", "Critical", "High", "Medium", "Low", "Confirmed", "Corrected", "Refuted", "Unverified")
    cov = ["# Coverage\n", "Generated by `build_index.py`. Source `findings` = verified file, `raw` = finder output only. "
           "Severity counts leave refuted findings out; Unverified are almost all Low findings the verifier skipped by design.\n",
           "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    tot = Counter()
    print("\t".join(head))
    for pkg in sorted(source):
        c = by_pkg[pkg]
        vals = (c["sev:Critical"], c["sev:High"], c["sev:Medium"], c["sev:Low"],
                c["CONFIRMED"], c["CORRECTED"], c["REFUTED"], c["UNVERIFIED"] + c["RAW"])
        for k, v in zip(head[2:], vals):
            tot[k] += v
        print("\t".join(str(x) for x in (pkg, source[pkg]) + vals))
        cov.append(f"| [{pkg}](../{source[pkg]}/{pkg}.md) | {source[pkg]} | " + " | ".join(str(v) for v in vals) + " |")
    cov.append("| **Total** | | " + " | ".join(f"**{tot[k]}**" for k in head[2:]) + " |")
    with open(os.path.join(out, "coverage.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(cov) + "\n")
    print("\t".join(["TOTAL", ""] + [str(tot[k]) for k in head[2:]]))
    print(f"total live {len(live)}, refuted {len(refuted)}", file=sys.stderr)


main()
