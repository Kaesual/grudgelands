--
-- Food (WP6/T7)
--
-- The Mirefolk drop "fish 1/1" (§3.1 swamp row); §6 lists "meat/fish
-- everywhere" as a food source for both continents. mobs_redo ships meat but
-- no fish, so this is our own item. NOT registered through material() above:
