	description = "Raw Fish",
	inventory_image = "grug_mobs_item_raw_fish.png",
	on_use = core.item_eat(3),
	groups = {food_fish_raw = 1},
	_grug_sell_price = 2,
})
mobs.add_eatable("grug_mobs:raw_fish", 3)
