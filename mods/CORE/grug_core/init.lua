--
-- Terrain-adaptive camp platform height. Decided exactly once per world and
-- per race capital, then persisted — a platform can never shift once built.
--
-- Source: core.get_spawn_level(x, z), the engine's own "where would a player
-- spawn here" query, resolved LAZILY on the first request. It is a pure
-- function of (x, z) served by the active Mapgen instance (l_mapgen.cpp ->
-- EmergeManager::getSpawnLevelAtPoint -> MapgenV7::getSpawnLevelAtPoint), so
-- it sees our mgv7_np_terrain_* overrides from grug_mapgen/init.lua and,
-- unlike the mapgen heightmap, does not depend on WHICH mapchunk happens to
-- ask, nor on the chunk's y range. That is the whole point: the previous
-- heightmap median could only be measured by the one mapchunk holding the
-- surface, which made both the value and the platform build order-dependent.
--
-- The engine answers with a PLAYER SPAWN level, which sits above the ground:
-- MapgenV7::getSpawnLevelAtPoint returns surface + 1 (allowance for full-node
-- biome 'dust'; + 2 when mgv7 runs with the `nomountains` flag) and
-- l_mapgen.cpp adds another + 1 ("'findSpawnPos()' in server.cpp adds at
-- least 1"). Our platform TOP layer has to end up AT the surface, hence -2.
--
-- nil means "unsuitable spawn point" and for mgv7 that is DETERMINISTIC, not
-- transient: inside a river channel, at/below water level, or wherever the
-- terrain rises above max(np_terrain_base.offset, np_terrain_alt.offset,
-- water_level + 16) — with our offsets that ceiling is y = 17, so a capital
-- on higher ground answers nil forever. Nothing is persisted then; the camp
-- pass falls back to the mapgen heightmap (grug_mapgen/structures.lua) and
-- every other caller keeps its CAMP_PLATFORM_Y fallback.
--
-- NB do not call this at load time: EmergeManager::getSpawnLevelAtPoint has
-- no mapgen before Server::init() runs initMapgens (server.cpp, after the
-- mods are loaded) and then answers 0, which arrives here as a bogus 1.
--

local SPAWN_LEVEL_TO_SURFACE = 2

local storage = core.get_mod_storage()

local function stored_platform_y(race_id)
	local y = storage:get_int("camp_platform_y:" .. race_id)
	if y == 0 then
		return nil -- not decided yet (real values are always >= 4)
	end
	return y
end

-- Terrain surface level at (x, z) as the engine sees it, or nil where mgv7
-- has no answer (see the long note above — that nil is permanent, not
-- transient, and every caller needs its own fallback). The -2 lives here so
-- the capital platforms and the WP6 outposts cannot drift apart.
function grug_core.surface_level_at(x, z)
	local level = core.get_spawn_level(x, z)
	if not level then
		return nil
	end
	return level - SPAWN_LEVEL_TO_SURFACE
end

function grug_core.get_camp_platform_y(race_id)
	local y = stored_platform_y(race_id)
	if y then
		return y
	end
	local capital = grug_core.capitals[race_id]
	if not capital then
		return nil
	end
	local level = grug_core.surface_level_at(capital.x, capital.z)
	if not level then
		return nil -- unsuitable point, see above: caller decides what to do
	end
	return grug_core.set_camp_platform_y(race_id, level)
end

-- Clamps y into the platform band, persists it (first writer wins — a
-- decided platform never moves) and returns the effective value.
function grug_core.set_camp_platform_y(race_id, y)
	local stored = stored_platform_y(race_id)
	if stored then
		return stored
	end
	y = math.min(math.max(math.floor(y), grug_core.CAMP_PLATFORM_Y),
		grug_core.CAMP_PLATFORM_MAX_Y)
	storage:set_int("camp_platform_y:" .. race_id, y)
	core.log("action",
		("[grug_core] %s capital platform decided at y=%d"):format(race_id, y))
	return y
end

-- Spawn position on the platform of a race capital (top layer + 1). An
-- unknown race — or one of the other faction (admin faction switch) —
-- falls back to the faction seat.
function grug_core.get_spawn_pos(faction_id, race_id)
	local faction = grug_core.factions[faction_id]
	local capital = race_id and grug_core.capitals[race_id]
	if not capital or capital.faction ~= faction_id then
		race_id = faction.seat_race
		capital = grug_core.capitals[race_id]
	end
	local y = grug_core.get_camp_platform_y(race_id)
		or grug_core.CAMP_PLATFORM_Y
	return vector.new(capital.x, y + 1, capital.z)
end

