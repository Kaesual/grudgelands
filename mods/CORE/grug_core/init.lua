grug_core = {}

-- World layout (docs/design/world.md §1): two separate continents, mirrored
-- at z = 0 — Elandor in the south (Accord, z negative) and Kragmar in the
-- north (Throng, z positive). Everything outside the two continent
-- rectangles is ocean: the strait along z = 0, the coastal ocean around
-- each continent and the deadly open sea beyond it (§2b).
--
-- The gameplay rectangle per faction is |x| <= CONTINENT_X_HALF and
-- CONTINENT_Z_MIN <= |z| <= CONTINENT_Z_MAX (3000x1600 by default). It is
-- the LEGAL bound (build rights, level field); the visible coastline is
-- soft and wanders inside it (grug_mapgen).
grug_core.CONTINENT_X_HALF = 1500
grug_core.CONTINENT_Z_MIN = 100 -- strait: |z| < 100 is always water
grug_core.CONTINENT_Z_MAX = 1700

-- Distance from a continent rectangle at which the coastal ocean ends and
-- the open sea (deadly guards, world.md §2b) begins.
grug_core.OCEAN_COASTAL_WIDTH = 1500

-- Derived geometry of one continent (all anchors below hang off the
-- constants above, so a world size change only touches them).
local X_HALF = grug_core.CONTINENT_X_HALF
local Z_MIN = grug_core.CONTINENT_Z_MIN
local Z_MAX = grug_core.CONTINENT_Z_MAX
-- Faction seat / continent center: (0, +-SEAT_Z).
local SEAT_Z = (Z_MIN + Z_MAX) / 2 -- 900
-- The safe core is a belt elongated along x (the three race capitals sit
-- side by side): inside |x| <= CORE_X_HALF the radial field ignores x.
local CORE_X_HALF = 300
-- Radial field scale: n = 1 (level 60) lands just short of the flank and
-- back coastlines, so the outermost land is elite everywhere. The z axis is
-- ASYMMETRIC: on the strait side of the seat the field must stretch (the
-- inner ring reaches down to z ~350, biomes_mobs §1.5 — otherwise players
-- walking to the 20-30 war coast would cross a lvl-35 belt first), while on
-- the back side the coast at dz = 800 has to reach 60.
local FIELD_X = 1150
local FIELD_Z_FRONT = 1000 -- strait side of the seat (|z| < SEAT_Z)
local FIELD_Z_BACK = 775 -- back side (|z| >= SEAT_Z)
-- War coast: the strait-facing band of a continent (world.md §1).
local WAR_COAST_Z = 300
-- The war-coast cap fades out as a ramp up to here, so the capped band
-- joins the radial field without a step (biomes_mobs §1.5: no >5 jumps).
local WAR_COAST_FADE_Z = 600
-- Coast band: the last nodes before a flank (|x|) or back (|z|) shoreline.
local COAST_BAND = 150
-- Below this depth every position counts as underground (cave content).
local UNDERGROUND_Y = -40

-- Race region bands along x within each continent (docs/design/world.md §7).
-- Bands overlap by 200 nodes; in the overlap the biome noise decides, which
-- gives an organic transition instead of a hard line.
grug_core.REGION_WEST_MAX = -500 -- west band: x <= -500
grug_core.REGION_CENTER_MIN = -700 -- center band: -700 <= x <= 700
grug_core.REGION_CENTER_MAX = 700
grug_core.REGION_EAST_MIN = 500 -- east band: x >= 500

-- Spawn camps (placeholder capitals until WP13 ships real structures):
-- a flat platform generated by grug_mapgen at every race capital. The
-- platform HEIGHT is terrain-adaptive: resolved lazily from the engine's
-- spawn level at the anchor (see below), persisted in mod storage — a fixed
-- y buried the camp inside hills (players spawned trapped in a pit).
grug_core.CAMP_HALF = 12 -- platform is (2*12+1)^2 nodes
grug_core.CAMP_PLATFORM_Y = 8 -- fallback/minimum platform y (above water)
grug_core.CAMP_PLATFORM_MAX_Y = 100 -- sanity cap (find_surface scans from 120)
grug_core.CAMP_CLEAR_HEIGHT = 64 -- air cleared this high above the platform

-- Vertical reach of every POI protection (world.md §2): a protected zone
-- starts this far BELOW the POI's base level and then runs upward without a
-- limit — nobody towers over a capital, nobody tunnels in right underneath
-- it, and deep mining below stays free. The horizontal extent belongs to the
-- POI: a spawn platform protects only its own footprint (CAMP_HALF), while
-- the real villages/outposts/capitals of WP13 also protect >= 10 nodes of
-- surrounding terrain.
grug_core.POI_PROTECT_DEPTH = 30

-- Three race capitals per continent (docs/design/world.md §3), all in the
-- safe-core belt: the central one (human/orc) is the faction seat, the
-- other two sit in their race's own band. Players spawn and respawn in
-- their OWN race's capital.
-- NB x/z are the ANCHOR of the capital; y comes from the terrain-adaptive
-- platform height — always go through grug_core.get_spawn_pos().
grug_core.capitals = {
	human = {faction = "accord", x = 0, z = -SEAT_Z, seat = true},
	dwarf = {faction = "accord", x = -550, z = -SEAT_Z},
	elf = {faction = "accord", x = 550, z = -SEAT_Z},
	orc = {faction = "throng", x = 0, z = SEAT_Z, seat = true},
	undead = {faction = "throng", x = -550, z = SEAT_Z},
	troll = {faction = "throng", x = 550, z = SEAT_Z},
}

-- Military outposts (docs/design/world.md §4 "one outpost per ring per
-- ~500 m east-west" and §9 "1 military outpost per ring as the guaranteed
-- minimum"): 18 DETERMINISTIC anchors, three per race band.
--
-- This table is the ONE source for them. grug_mapgen/structures.lua builds
-- the pad + guard banner at these positions, grug_mobs/camps.lua reads the
-- patrol neighbour off the same list, and the POI protection registry is fed
-- from the mapgen pass — nobody re-derives the formula anywhere else.
--
-- x = the race capital's x (the outpost belongs to its race band, §9 budget),
-- z = the capital's z sign times the ring radius, so the two continents are
-- exact mirrors of each other, like everything else in this file.
--
-- RING RADII, sanity-checked against grug_core.zone_at below (the numbers in
-- brackets are the constants at the top of this file):
--   war_coast |z| = 250  -> Z_MIN(100) < 250 <= WAR_COAST_Z(300), so zone_at
--                           answers "war_coast" for all six — the PvP stage
--                           of world.md §1, capped at mob level ~27.
--   inner     |z| = 500  -> past the war-coast band, 1200 nodes clear of the
--                           back coast band (Z_MAX - COAST_BAND = 1550) and
--                           |x| <= 550 is nowhere near the flank band, so the
--                           radial field decides: n = 0.40 (centre capitals)
--                           .. 0.46 (side capitals), i.e. 0.30 < n <= 0.55
--                           -> "inner".
--   outer     |z| = 1350 -> still 200 nodes inside the back coast band, so
--                           again the radial field: n = 0.58 .. 0.62 > 0.55
--                           -> "outer".
-- (Verified numerically for all 18 anchors; the acceptance run is quoted in
-- the WP6/T8 report.)
--
-- The vertical size is NOT here: an outpost's y is terrain-adaptive and gets
-- decided (and persisted as the POI's y_base) by the mapgen pass, exactly
-- like the capital platforms above.
grug_core.OUTPOST_HALF = 4 -- 7x7 pad (half 3) plus one node of breathing room

-- Ring radius and the patrol partner of each ring (world.md §4 "between
-- outposts: ambient patrols"). The pairing always walks TOWARD the strait —
-- outer -> inner -> war_coast — and the war-coast post, which has no ring in
-- front of it, walks back to the inner one, so every band ends up with two
-- patrolled legs and no dead end.
local OUTPOST_RINGS = {
	{ring = "war_coast", radius = 250, patrol_to = "inner"},
	{ring = "inner", radius = 500, patrol_to = "war_coast"},
	{ring = "outer", radius = 1350, patrol_to = "inner"},
}

-- Built once at load time (pure arithmetic on the capitals table). The race
-- ids are sorted so the list order is reproducible across runs — pairs() over
-- the capitals would not be.
local outpost_list = {}
local outpost_by_id = {}

do
	local races = {}
	for race_id in pairs(grug_core.capitals) do
		races[#races + 1] = race_id
	end
	table.sort(races)
	for _, race_id in ipairs(races) do
		local capital = grug_core.capitals[race_id]
		local sign = capital.z >= 0 and 1 or -1
		for _, ring in ipairs(OUTPOST_RINGS) do
			local anchor = {
				id = "outpost:" .. capital.faction .. ":" .. race_id ..
					":" .. ring.ring,
				faction = capital.faction,
				race = race_id,
				ring = ring.ring,
				patrol_to = ring.patrol_to,
				x = capital.x,
				z = sign * ring.radius,
			}
			outpost_list[#outpost_list + 1] = anchor
			outpost_by_id[anchor.id] = anchor
		end
	end
end

-- The full anchor list. READ-ONLY for callers (it is the shared table, not a
-- copy — copying it per mapchunk would be pure garbage).
function grug_core.outpost_anchors()
	return outpost_list
end

function grug_core.get_outpost(id)
	return outpost_by_id[id]
end

-- The outpost anchor whose footprint contains pos (x/z only — an outpost's y
-- is terrain-adaptive), or nil. Used by the guard camp to find out WHICH
-- outpost its banner stands on; a banner elsewhere (the capital watch of
-- world.md §3) simply gets no patrol route.
function grug_core.outpost_at(pos)
	local half = grug_core.OUTPOST_HALF
	for i = 1, #outpost_list do
		local a = outpost_list[i]
		if math.abs(pos.x - a.x) <= half and math.abs(pos.z - a.z) <= half then
			return a
		end
	end
	return nil
end

-- Patrol partner of an outpost anchor (see OUTPOST_RINGS): the adjacent
-- outpost of the SAME race band one ring further toward the strait.
function grug_core.outpost_patrol_target(anchor)
	if not anchor or not anchor.patrol_to then
		return nil
	end
	return outpost_by_id["outpost:" .. anchor.faction .. ":" .. anchor.race ..
		":" .. anchor.patrol_to]
end

