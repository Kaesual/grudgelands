--
-- Position fields (docs/design/world.md §1, biomes_mobs.md §1.1).
--

-- "accord" (southern continent), "throng" (northern continent) or "ocean"
-- (strait, coastal ocean, open sea — everything outside both rectangles).
function grug_core.territory_at(pos)
	if math.abs(pos.x) <= X_HALF then
		local z = pos.z
		if z >= Z_MIN and z <= Z_MAX then
			return "throng"
		elseif z <= -Z_MIN and z >= -Z_MAX then
			return "accord"
		end
	end
	return "ocean"
end

-- Radial field value around the faction seat of the nearer continent:
-- 0 at the seat, ~1 at the flank/back coastlines. The core belt is
-- elongated along x, so the three race capitals share one low-level zone;
-- the z axis uses the wider FRONT scale toward the strait (see above).
local function radial_n(pos)
	local az = math.abs(pos.z)
	local dx = math.max(math.abs(pos.x) - CORE_X_HALF, 0)
	local dz = math.abs(az - SEAT_Z)
	local field_z = az < SEAT_Z and FIELD_Z_FRONT or FIELD_Z_BACK
	return math.sqrt((dx / FIELD_X) ^ 2 + (dz / field_z) ^ 2)
end

-- Zone name at pos (the `_grug_spawn_zones` vocabulary, biomes_mobs §1.1):
-- "underground", "ocean", "strait", "war_coast", "coast", "core", "inner"
-- or "outer". Depth wins everywhere — caves are cave content regardless of
-- what lies above them.
function grug_core.zone_at(pos)
	if pos.y < UNDERGROUND_Y then
		return "underground"
	end
	local az = math.abs(pos.z)
	if grug_core.territory_at(pos) == "ocean" then
		if az > Z_MIN then
			return "ocean"
		end
		return "strait"
	end
	if az <= Z_MIN then
		return "strait"
	end
	if az <= WAR_COAST_Z then
		return "war_coast"
	end
	if X_HALF - math.abs(pos.x) <= COAST_BAND or Z_MAX - az <= COAST_BAND then
		return "coast"
	end
	local n = radial_n(pos)
	if n <= 0.30 then
		return "core"
	elseif n <= 0.55 then
		return "inner"
	end
	return "outer"
end

-- Mob level anchors on the radial field (world.md §1): safe core 1-10,
-- inner ring 10-25, outer ring 25-45, flank/back coasts up to 60.
local level_anchors = {
	{n = 0, level = 1},
	{n = 0.30, level = 10},
	{n = 0.55, level = 25},
	{n = 0.90, level = 45},
	{n = 1.00, level = 60},
}

-- Level of the mob field at radial value n, piecewise linear between the
-- anchors; everything beyond the last anchor stays at 60.
local function level_at_n(n)
	for i = 1, #level_anchors - 1 do
		local a, b = level_anchors[i], level_anchors[i + 1]
		if n <= b.n then
			return a.level + (n - a.n) / (b.n - a.n) * (b.level - a.level)
		end
	end
	return level_anchors[#level_anchors].level
end

-- War-coast cap (world.md §1): the strait-facing PvP stage stays at 20-30
-- up to |z| = WAR_COAST_Z, then the cap RAMPS to 60 until WAR_COAST_FADE_Z,
-- where it becomes a no-op. Without that ramp the capped band ended in an
-- 8-30 level step at |z| = 300 (biomes_mobs §1.5: no jumps > 5).
local function war_coast_cap(az)
	if az <= WAR_COAST_Z then
		return 20 + (az - Z_MIN) / (WAR_COAST_Z - Z_MIN) * 10
	end
	return 30 + (az - WAR_COAST_Z) / (WAR_COAST_FADE_Z - WAR_COAST_Z) * 30
end

-- Mob level for a hostile spawned at pos (1..60), or nil on the open water
-- surface (no leveled hostiles there; the deep-sea guards of world.md §2b
-- are hand-set). Radial field from the faction seat, then the two caps of
-- world.md §1 (war coast, strait) and the depth axis of combat_stats.md §3
-- — the safe core is only safe on the surface.
function grug_core.mob_level_at(pos)
	local ocean = grug_core.territory_at(pos) == "ocean"
	local az = math.abs(pos.z)
	-- Open/coastal sea surface only — the strait (|z| <= Z_MIN) keeps its
	-- level so its neutral wildlife (gulls/crabs, 1-5) has one.
	if ocean and az > Z_MIN and pos.y >= 0 then
		return nil
	end
	local level = level_at_n(radial_n(pos))
	if not ocean and az > Z_MIN and az <= WAR_COAST_FADE_Z then
		level = math.min(level, war_coast_cap(az))
	elseif az <= Z_MIN then
		level = math.min(level, 5) -- strait & beaches: harmless wildlife
	end
	if pos.y < 0 then
		level = math.max(level, math.min(60, 1 + math.floor(-pos.y / 20)))
	end
	return math.round(level)
end

-- Guard level at pos (20..70, WP6), or nil in the ocean. Runs INVERSE to
-- the mob field (world.md §1): elite city watch (60+) at the faction seat
-- and in the safe core, ~local mob level + 5 at the war coast — pushing
-- deeper means weaker mobs but ever harder guards.
function grug_core.guard_level_at(pos)
	if grug_core.territory_at(pos) == "ocean" then
		return nil
	end
	local level = math.max(65 - 45 * radial_n(pos),
		(grug_core.mob_level_at(pos) or 0) + 5)
	-- Elite city watch floor: world.md §1/§3 promise 60+ in ALL three race
	-- capitals and across the safe core, but the plain inverse field only
	-- reaches ~55 at the side capitals (x = +-550). zone_at runs on a
	-- SURFACE copy of pos — underground positions report "underground" and
	-- would otherwise lose the floor under the capitals.
	if grug_core.zone_at(vector.new(pos.x, 8, pos.z)) == "core" then
		level = math.max(level, 60)
	end
	return math.round(math.min(70, math.max(20, level)))
end

-- 0 (safe core) .. 1 (elite coasts), defined as (mob_level-1)/59 and
-- clamped; positions without a mob level (open water surface) count as 1.
function grug_core.difficulty_at(pos)
	local level = grug_core.mob_level_at(pos)
	if not level then
		return 1
	end
	return math.min(1, math.max(0, (level - 1) / 59))
end

-- Chebyshev distance from one continent rectangle (0 inside it).
local function rect_distance(pos, z_min, z_max)
	local ddx = math.max(math.abs(pos.x) - X_HALF, 0)
	local ddz = math.max(z_min - pos.z, pos.z - z_max, 0)
	return math.max(ddx, ddz)
end

-- True beyond the coastal ocean of BOTH continents (world.md §2b): the
-- open sea, where the oversized deep-sea guards live.
function grug_core.open_sea_at(pos)
	local d = math.min(rect_distance(pos, Z_MIN, Z_MAX),
		rect_distance(pos, -Z_MAX, -Z_MIN))
	return d > grug_core.OCEAN_COASTAL_WIDTH
end

