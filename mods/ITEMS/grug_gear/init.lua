-- Vendor bracket gear (docs/design/items_crafting.md §3.8, curves §3.1/§3.2,
-- prices §8.2). Six catalogs, one per ten character levels; a player sees
-- their own bracket and every bracket below it.
--
-- Everything in here is GENERATED from the design curves, never hand-listed:
-- 4 weapon families x 6 brackets = 24 tools, plus 2 armor lines x 4 slots x
-- 6 brackets = 48 craftitems. All Common, therefore all without enchants
-- (§3.8) and 10-15% behind crafted gear of the same era by construction.
--
-- ---------------------------------------------------------------------------
-- ITEM-LEVEL INTERFACE
-- ---------------------------------------------------------------------------
--   _grug_ilvl     The item level of the bracket. grug_inventory enforces it
--                  as the minimum level for the weapon slot
--                  (inventory_equipment.md §2, items_crafting.md §6.1).
--                  Items without an ilvl, including the starter weapons and
--                  tool-ladder axes, remain unrestricted.
--   _grug_quality  1 = Common for every item registered here. WP5 owns
--                  quality > 1, the enchant roll ranges behind it (§6.2/§6.3)
--                  and the colored display names that come with it. Nothing
--                  in WP7 rolls quality; the x3-priced rotating Uncommon of
--                  §3.8 is the trader task's job on top of WP5's roller.
-- ---------------------------------------------------------------------------
--
-- Trader interface (consumed by the vendor task): grug_gear.BRACKETS,
-- grug_gear.bracket_for_level, grug_gear.get_price, grug_gear.get_sell_price
-- and grug_gear.catalog. Rotation, vendors and UI live there, not here.
--
-- Textures: 16px originals of this project (CC0), generated by
-- tools/gen_mob_item_textures.py -- see LICENSE-media.md.

