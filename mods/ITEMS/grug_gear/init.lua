-- Item description (§6.1): name, item level, then the BASE stat line -- the
-- number the item actually contributes, so a player can compare two pieces
-- without doing the curve in their head. Grey, because it is derived data
-- rather than part of the name.
--
-- WP5 NOTE: when the enchant roller starts regenerating descriptions from
-- meta, it must KEEP these two lines and append one line per enchant below
-- them (§6.1) -- the base stat does not live in meta and cannot be
-- reconstructed from the roll.
--
-- No colorize on the name itself: Common is plain white, WP5 owns the
-- quality colors.
local STAT_COLOR = "#9aa0a6"

local function describe(material, noun, ilvl, stat_line)
	local name = noun and (material .. " " .. noun) or material
	local level_line = ilvl and ("\nItem level " .. ilvl) or ""
	return name .. level_line ..
		"\n" .. core.colorize(STAT_COLOR, stat_line)
end

-- "5 damage, 1.0 s swing" -- full_punch_interval is the authoritative
-- soft-lock clock interval for swing abilities and the native fraction's
-- denominator for ordinary tools/fists (combat_stats.md §2), so it belongs
-- next to the damage number: a dagger
-- doing less per swing but swinging faster is otherwise invisible.
--
-- Two-handed weapons say so HERE as well as in the equip refusal (B4): the
-- rule costs a greataxe user their offhand torch, and combat_stats.md §7 wants
-- that to be a decision, not a surprise. The refusal explains it at the moment
-- it bites; this line lets a player see it before they buy the thing.
local function weapon_stats(damage, fpi, hands)
	local line = string.format("%d damage, %.1f s swing", damage, fpi)
	if hands >= 2 then
		line = line .. ", two-handed"
	end
	return line
end

-- "3 armor (-3% damage taken)" -- 1 armor point = 1% reduction
-- (items_crafting.md §3.1), capped at 60% across all four pieces.
local function armor_stats(armor)
	return string.format("%d armor (-%d%% damage taken)", armor, armor)
end

--
-- Weapons (§3.2). Base 1H damage curve; the family factor multiplies the
-- ROUNDED 1H value, exactly as the §3.2 table is built.
--
-- Verified against the §3.8 row: ilvl 3/10/20/30/40/50 -> 5/8/11/15/18/22.
--
-- How damage reaches a mob (WP38): a swing ability builds one authoritative
-- full hit from this fleshy value + floor(Str/10) at this interval, then armor
-- and one crit roll. Ordinary wielded tools/fists keep mobs_redo's proportional
-- `clamp(tflp/fpi, 0, 1)` path. `full_punch_interval` is therefore both the
-- ability clock and the ordinary path's damage-scaler denominator;
-- `damage_groups.fleshy` is one full swing's base strength.
--

local function dmg1h(ilvl)
	return math.floor(4 + 0.35 * ilvl + 0.5)
end

-- `hands` is published as `_grug_hands` and enforced by grug_inventory's equip
-- filter (weapon-slot design B4, combat_stats.md §7): a two-handed weapon
-- needs an empty offhand and blocks the offhand while equipped. It is a
-- DECLARATION here, never a check -- grug_gear registers items, the equipment
-- lists are the only place that knows what a free hand is.
--
-- greataxe and staff are the two-handers; sword and dagger are one-handed, and
-- so is the caster 1H (wand/tome) once §3.2's caster family exists. Anything
-- that does not declare the field at all counts as one-handed, which is what
-- keeps the rule additive for torches, shields and every future offhand item.
local WEAPONS = {
	-- `fixed` = always on sale; the rest are the rotation pool of §3.8.
	{key = "sword",    noun = "Sword",    fpi = 1.0, factor = 1.0, hands = 1, group = "sword", fixed = true},
	{key = "dagger",   noun = "Dagger",   fpi = 0.7, factor = 0.7, hands = 1, group = "sword"},
	{key = "greataxe", noun = "Greataxe", fpi = 1.4, factor = 1.5, hands = 2, group = "axe"},
	{key = "staff",    noun = "Staff",    fpi = 1.4, factor = 1.2, hands = 2, group = "staff"},
}

--
-- Armor (§3.1). Set totals are linear fits through the tier table
-- (T1..T4 at ilvl 12/27/42/57), verified in Lua before the coefficients were
-- committed to:
--
--   metal   ilvl 12/27/42/57 -> 16.00 / 29.00 / 42.00 / 55.00  (doc 16/29/42/55) exact
--   cloth   ilvl 12/27/42/57 ->  5.00 /  8.33 / 11.67 / 15.00  (doc  5/ 8/11/15)
--   leather ilvl 12/27/42/57 -> 11.00 / 20.67 / 30.33 / 40.00  (doc 11/20/30/40)
--
-- Two doc cells do not round to their table value: cloth at ilvl 42 rounds
-- to 12 (doc 11) and leather at ilvl 27 rounds to 21 (doc 20). Both are
-- interior points of a fit anchored on T1/T4 -- reported as findings; the
-- vendor brackets stop at ilvl 50 and none of them touches those cells.
--
-- Only metal and cloth ship (decided 2026-08-07): the MVP classes are
-- Warrior (rank 3) / Mage (rank 1) / Priest (rank 1), so nothing can wear
-- rank 2 and 24 leather items would be dead weight. The leather curve stays
-- here so the coefficients never have to be re-derived -- it is registered
-- with the Rogue (Phase 2) / the WP5 drop tables.
--

local ARMOR_LINES = {
	{key = "metal", rank = 3, base = 5.6, per_ilvl = 0.86667, register = true,
		nouns = {head = "Helm", chest = "Chestplate", legs = "Greaves", feet = "Sabatons"}},
	{key = "leather", rank = 2, base = 3.2667, per_ilvl = 0.64444, register = false,
		nouns = {head = "Hood", chest = "Jerkin", legs = "Pants", feet = "Boots"}},
	{key = "cloth", rank = 1, base = 2.3333, per_ilvl = 0.22222, register = true,
		nouns = {head = "Cowl", chest = "Robe", legs = "Leggings", feet = "Slippers"}},
}

-- Per-piece split of the set total (§3.1: chest/legs/head/feet 35/27/22/16%).
local ARMOR_SLOTS = {
	{key = "head",  share = 0.22},
	{key = "chest", share = 0.35},
	{key = "legs",  share = 0.27},
	{key = "feet",  share = 0.16},
}

--
-- Prices. `get_price` is what the player pays a vendor, `get_sell_price` the
-- vendor buy-back at 25% (also mirrored into `_grug_sell_price`, the field
-- every trader already reads on mob drops).
--

local buy_price = {}
local sell_price = {}

local function buyback(price)
	return math.max(1, math.floor(price * 0.25))
end

-- copper, or nil for anything that is not vendor gear
function grug_gear.get_price(itemname)
	return buy_price[itemname]
end

function grug_gear.get_sell_price(itemname)
	return sell_price[itemname]
end

--
-- Generation.
--

grug_gear.catalog = {}

-- The one place an item NAME is built from a family and a tier. Every consumer
-- that knows a family and a bracket -- grug_visuals' `weapon_family` shorthand
-- for the guards and bandits, the gear-catalogue KAT, a later drop table --
-- asks here instead of concatenating `_b<n>` (which is exactly what this round
-- renamed away).
function grug_gear.weapon_item(family, bracket)
	local material = grug_gear.MATERIALS[bracket]
	if type(family) ~= "string" or not material then
		return nil
	end
	return "grug_gear:" .. family .. "_" .. material.metal.key
end

function grug_gear.armor_item(slot, line, bracket)
	local material = grug_gear.MATERIALS[bracket]
	if type(slot) ~= "string" or not material or not material[line] then
		return nil
	end
	return "grug_gear:" .. slot .. "_" .. line .. "_" .. material[line].key
end

local tool_count, craftitem_count = 0, 0

for bracket, br in ipairs(grug_gear.BRACKETS) do
	local cat = {fixed = {}, extras = {}, all = {}}
	grug_gear.catalog[bracket] = cat

	local tint = "^[multiply:" .. BRACKET_TINT[bracket]
	local base_damage = dmg1h(br.ilvl)
	local metal = grug_gear.MATERIALS[bracket].metal

	for _, w in ipairs(WEAPONS) do
		local itemname = grug_gear.weapon_item(w.key, bracket)
		local damage = math.max(1, math.floor(base_damage * w.factor + 0.5))
		-- Every weapon family is weapon-slot eligible (weapon-slot design B3).
		-- No class gate: weapon families are class FLAVOR, not a power ladder
		-- (§8.2), so a Mage may equip a greataxe and simply gains nothing from
		-- it; the only gate on the slot is the `_grug_ilvl` minimum. The slot
		-- itself is family-agnostic, which is how the future bow family joins
		-- without a second slot.
		local groups = {grug_gear = 1, grug_equip_weapon = 1}
		groups[w.group] = 1
		core.register_tool(itemname, {
			description = describe(metal.name, w.noun, br.ilvl,
				weapon_stats(damage, w.fpi, w.hands)),
			-- One sprite per family AND material, all in the one diagonal
			-- convention (grip bottom-left) the wield transform is derived for.
			inventory_image = "grug_gear_item_" .. w.key .. "_" ..
				metal.key .. ".png",
			groups = groups,
			stack_max = 1,
			tool_capabilities = {
				full_punch_interval = w.fpi,
				damage_groups = {fleshy = damage},
				max_drop_level = 0,
				groupcaps = {},
			},
			_grug_ilvl = br.ilvl,
			_grug_bracket = bracket,
			_grug_quality = 1,
			_grug_hands = w.hands,
			_grug_sell_price = buyback(br.price.weapon),
		})
		buy_price[itemname] = br.price.weapon
		sell_price[itemname] = buyback(br.price.weapon)
		table.insert(w.fixed and cat.fixed or cat.extras, itemname)
		tool_count = tool_count + 1
	end

	for _, line in ipairs(ARMOR_LINES) do
		if line.register then
			local total = line.base + line.per_ilvl * br.ilvl
			local grade = grug_gear.MATERIALS[bracket][line.key]
			for _, slot in ipairs(ARMOR_SLOTS) do
				local itemname = grug_gear.armor_item(slot.key, line.key, bracket)
				-- max(1) is a deliberate deviation from the raw split: at the
				-- low cloth brackets the 16% foot share rounds to 0, and a
				-- 0-armor boot is a bug, not a design statement.
				local armor = math.max(1, math.floor(total * slot.share + 0.5))
				local price = br.price.other
				if slot.key == "chest" then
					price = br.price.chest
				end
				core.register_craftitem(itemname, {
					description = describe(grade.name, line.nouns[slot.key],
						br.ilvl, armor_stats(armor)),
					inventory_image = "grug_gear_item_" .. slot.key .. "_" ..
						line.key .. ".png" .. tint,
					groups = {
						["grug_equip_" .. slot.key] = 1,
						grug_armor_class = line.rank,
						grug_gear = 1,
					},
					stack_max = 1,
					_grug_armor = armor,
					_grug_ilvl = br.ilvl,
					_grug_bracket = bracket,
					_grug_quality = 1,
					_grug_sell_price = buyback(price),
				})
				buy_price[itemname] = price
				sell_price[itemname] = buyback(price)
				table.insert(cat.fixed, itemname)
				craftitem_count = craftitem_count + 1
			end
		end
	end

	-- `all` = the full bracket (12 items), the pool the Uncommon roll of
	-- §3.8 draws from; fixed first so the order stays stable for the UI.
	for _, itemname in ipairs(cat.fixed) do
		table.insert(cat.all, itemname)
	end
	for _, itemname in ipairs(cat.extras) do
		table.insert(cat.all, itemname)
	end
end

